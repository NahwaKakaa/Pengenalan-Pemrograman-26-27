// Evaluasi Modul 2 - Soal 5: Demonstrasi operator aritmatika
#include <iostream>
using namespace std;

int main() {
    int x = 17, y = 5;

    cout << "x = " << x << ", y = " << y << endl;
    cout << "x + y = " << x + y << endl;
    cout << "x - y = " << x - y << endl;
    cout << "x * y = " << x * y << endl;
    cout << "x / y = " << x / y << "   (pembagian bilangan bulat)" << endl;
    cout << "x % y = " << x % y << "   (sisa pembagian)" << endl;
    return 0;
}
