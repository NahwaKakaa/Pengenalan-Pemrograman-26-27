// Evaluasi Modul 2 - Soal 6
// int hasil = 5 + 2 * 3;  -> 2 * 3 dikerjakan dulu (6), lalu 5 + 6 = 11
#include <iostream>
using namespace std;

int main() {
    int hasil = 5 + 2 * 3;
    cout << "5 + 2 * 3   = " << hasil << endl;          // 11
    cout << "(5 + 2) * 3 = " << (5 + 2) * 3 << endl;    // 21, pembanding
    return 0;
}
