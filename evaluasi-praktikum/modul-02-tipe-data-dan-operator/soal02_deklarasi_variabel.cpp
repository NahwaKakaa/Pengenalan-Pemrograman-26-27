// Evaluasi Modul 2 - Soal 2: Deklarasi variabel data mahasiswa
#include <iostream>
using namespace std;

int main() {
    int umur = 19;               // umur mahasiswa (bilangan bulat)
    double nilaiRataRata = 3.65; // nilai rata-rata (pecahan)
    char jenisKelamin = 'L';     // jenis kelamin (satu karakter: L/P)
    bool statusAktif = true;     // status aktif (benar/salah)
    int jumlahSKS = 20;          // jumlah SKS (bilangan bulat)

    cout << "Umur           : " << umur << endl;
    cout << "Nilai rata-rata: " << nilaiRataRata << endl;
    cout << "Jenis kelamin  : " << jenisKelamin << endl;
    cout << "Status aktif   : " << statusAktif << endl;
    cout << "Jumlah SKS     : " << jumlahSKS << endl;
    return 0;
}
