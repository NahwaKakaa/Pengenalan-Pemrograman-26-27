// Modul 2 - Program 3: Konstanta dan Luas Lingkaran
#include <iostream>
using namespace std;

int main() {
    const double PI = 3.14159;
    const double r = 7.0;
    double luas = PI * r * r;

    cout << "PI = " << PI << endl;
    cout << "r = 7.0" << endl;
    cout << "Luas Lingkaran = " << PI << " * 7.0 * 7.0 = " << luas << endl;
    return 0;
}
