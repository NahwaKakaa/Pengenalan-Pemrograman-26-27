// Modul 2 - Program 1: Eksplorasi Tipe Data
#include <iostream>
using namespace std;

int main() {
    int jumlah = 25;
    double harga = 12500.50;
    char kategori = 'A';
    bool tersedia = true;

    cout << "jumlah   (int)    = " << jumlah << endl;
    cout << "harga    (double) = " << harga << endl;
    cout << "kategori (char)   = " << kategori << endl;
    cout << "tersedia (bool)   = " << tersedia << endl;   // true ditampilkan sebagai 1
    return 0;
}
